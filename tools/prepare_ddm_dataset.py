#!/usr/bin/env python3
"""Build a DDM-Net training dataset from per-video `step_segments.json` files.

Scans `data/**/step_segments.json` (generated by `tools/process_step_segments.py`),
splits videos into train/val sets, converts segments to the DDM-Net annotation
format, and writes everything under an output directory:

    <out-dir>/train_annotation.json
    <out-dir>/val_annotation.json
    <out-dir>/videos/<video_unique_id>.mp4   (symlinks to the source .mp4 files)

Two split modes are supported:
  - random:    random split by video (--val-ratio, --seed)
  - by_folder: explicit val set given by cd folder names (--val-folders cd18,cd19,cd20)

Usage:
    python tools/prepare_ddm_dataset.py --split-mode random --val-ratio 0.2 --seed 42
    python tools/prepare_ddm_dataset.py --split-mode by_folder --val-folders cd18,cd19,cd20
"""
from __future__ import annotations

import argparse
import json
import random
from pathlib import Path


def find_videos(data_dir: Path) -> list[Path]:
    """Return sorted paths to every chuyen directory that has step_segments.json."""
    return sorted(p.parent for p in data_dir.rglob("step_segments.json"))


def video_unique_id(video_dir: Path) -> str:
    # e.g. data/cd1/chuyen1 -> "cd1_chuyen1"
    return f"{video_dir.parent.name}_{video_dir.name}"


def find_mp4(video_dir: Path) -> Path | None:
    mp4s = list(video_dir.glob("*.mp4"))
    return mp4s[0] if mp4s else None


def to_ddm_events(step_segments: dict) -> list[dict]:
    events = []
    for seg in step_segments.get("segments", []):
        name = seg.get("operation_name", "") or "UNKNOWN"
        events.append(
            {
                "event": name,
                "description": name,
                "start_timestamp": seg["start_time_s"],
                "end_timestamp": seg["end_time_s"],
            }
        )
    return events


def split_videos(
    video_dirs: list[Path],
    split_mode: str,
    val_ratio: float,
    val_folders: list[str],
    seed: int,
) -> tuple[list[Path], list[Path]]:
    if split_mode == "by_folder":
        val_set = set(val_folders)
        val = [d for d in video_dirs if d.parent.name in val_set]
        train = [d for d in video_dirs if d.parent.name not in val_set]
        return train, val

    # random split by video
    rng = random.Random(seed)
    shuffled = video_dirs.copy()
    rng.shuffle(shuffled)
    n_val = max(1, round(len(shuffled) * val_ratio))
    val = shuffled[:n_val]
    train = shuffled[n_val:]
    return train, val


def build_annotation(video_dirs: list[Path], videos_out_dir: Path) -> dict:
    annotation = {}
    for video_dir in video_dirs:
        mp4_path = find_mp4(video_dir)
        if mp4_path is None:
            print(f"WARNING: no .mp4 found in {video_dir}, skipping")
            continue

        step_segments = json.loads((video_dir / "step_segments.json").read_text())
        events = to_ddm_events(step_segments)
        if not events:
            print(f"WARNING: no segments in {video_dir}, skipping")
            continue

        vid = video_unique_id(video_dir)
        annotation[vid] = events

        link_path = videos_out_dir / f"{vid}.mp4"
        if link_path.exists() or link_path.is_symlink():
            link_path.unlink()
        link_path.symlink_to(mp4_path.resolve())

    return annotation


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path, default=Path("data"))
    parser.add_argument("--out-dir", type=Path, default=Path("data/ddm_dataset"))
    parser.add_argument("--split-mode", choices=["random", "by_folder"], default="random")
    parser.add_argument("--val-ratio", type=float, default=0.2)
    parser.add_argument("--val-folders", type=str, default="", help="Comma-separated cd folder names, e.g. cd18,cd19,cd20")
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    video_dirs = find_videos(args.data_dir)
    if not video_dirs:
        print(f"No step_segments.json found under {args.data_dir}. Run tools/process_step_segments.py first.")
        return

    val_folders = [f.strip() for f in args.val_folders.split(",") if f.strip()]
    if args.split_mode == "by_folder" and not val_folders:
        raise ValueError("--split-mode by_folder requires --val-folders")

    train_dirs, val_dirs = split_videos(video_dirs, args.split_mode, args.val_ratio, val_folders, args.seed)
    print(f"Found {len(video_dirs)} videos -> train={len(train_dirs)}, val={len(val_dirs)}")

    videos_out_dir = args.out_dir / "videos"
    videos_out_dir.mkdir(parents=True, exist_ok=True)

    train_anno = build_annotation(train_dirs, videos_out_dir)
    val_anno = build_annotation(val_dirs, videos_out_dir)

    train_path = args.out_dir / "train_annotation.json"
    val_path = args.out_dir / "val_annotation.json"
    train_path.write_text(json.dumps(train_anno, ensure_ascii=False, indent=2))
    val_path.write_text(json.dumps(val_anno, ensure_ascii=False, indent=2))

    print(f"Wrote {len(train_anno)} train videos -> {train_path}")
    print(f"Wrote {len(val_anno)} val videos -> {val_path}")
    print(f"Videos symlinked under {videos_out_dir}")


if __name__ == "__main__":
    main()
